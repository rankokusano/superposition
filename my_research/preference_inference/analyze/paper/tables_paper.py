"""
Paper tables (paper round 1; documents only, CPU). Writes tabular-only .tex files (booktabs) into paper/tables/:
  conditions, metrics, group_values, projection, inverse, gates, module, alignment.
Numbers come from saved results (JSON) or, where noted in paper/tables/README.md, from the docs (*_summary.md,
*_results_log.md). No version numbers inside the tables. Every file is checked to encode as iso2022_jp.
"""

