def sg(x, d=3):
    """signed number in math mode, e.g. $+0.474$ / $-0.049$"""
    return f'${x:+.{d}f}$'


def rg(a, b, d=3, signed=False):
    if signed:
        return f'{sg(a, d)}〜{sg(b, d)}'
    return f'{a:.{d}f}〜{b:.{d}f}'


def ci(lo, hi, d=3, signed=True):
    f = (lambda v: sg(v, d)) if signed else (lambda v: f'{v:.{d}f}')
    return f'[{f(lo)}, {f(hi)}]'


def write(name, body):
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, name + '.tex')
    header = f'% paper/tables/{name}.tex -- generated by analyze/paper/tables_paper.py; sources in paper/tables/README.md\n'
    text = header + body.strip() + '\n'
    text.encode('iso2022_jp')        # raises if a character is outside JIS X 0208
    open(path, 'w', encoding='utf-8').write(text)
    print('wrote', path)


